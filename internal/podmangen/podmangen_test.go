func TestRenderQuadletFull(t *testing.T) {
	unit := RenderQuadlet(fullInput())
	if unit.Filename != "solmq-connector.container" {
		t.Errorf("filename = %q, want %q", unit.Filename, "solmq-connector.container")
	}
	want := `# Generated by solmq-conn-util -- podman quadlet unit for the Solace PubSub+ Connector for IBM MQ.
[Unit]
Description=Solace PubSub+ Connector for IBM MQ (solmq-connector)
After=network-online.target
Wants=network-online.target

[Container]
Image=solace/solace-pubsub-connector-ibmmq:2.13.0
ContainerName=solmq-connector
PublishPort=8090:8090
PublishPort=8080:8091
Environment=TZ=Asia/Singapore
Environment=JAVA_TOOL_OPTIONS=-Dcom.ibm.mq.cfg.useIBMCipherMappings=false
Secret=solmq-connector-MQ_CONN_1_USER,type=mount,target=MQ_CONN_1_USER
Secret=solmq-connector-MQ_CONN_1_PASSWORD,type=mount,target=MQ_CONN_1_PASSWORD
Volume=./solmq-connector-application.yml:/app/external/spring/config/application.yml:ro
Volume=/abs/certs/truststore.jks:/app/external/classpath/truststores/truststore.jks:ro
Volume=/abs/libs:/app/external/libs:ro

[Service]
Restart=unless-stopped

[Install]
WantedBy=default.target
`
	if unit.Content != want {
		t.Errorf("RenderQuadlet full mismatch:\n--- got ---\n%s\n--- want ---\n%s", unit.Content, want)
	}
}

